-- ---------- Tables ----------

create table if not exists categories (
  key        text primary key,
  label      text not null,
  icon       text not null default '🛍️',
  blurb      text not null default '',
  image      text,
  sort       int  not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists products (
  id          bigint generated by default as identity primary key,
  name        text not null,
  category    text references categories(key) on update cascade on delete cascade,
  emoji       text not null default '🛍️',
  image       text,
  images      text[] not null default '{}',
  description text,
  price       numeric not null check (price >= 0),
  old_price   numeric,
  featured    boolean not null default false,
  new_arrival boolean not null default false,
  stock       int not null default 0 check (stock >= 0),
  rating      numeric not null default 5,
  created_at  timestamptz not null default now()
);

-- One row per signed-up user (customers and admins)
create table if not exists profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text,
  first_name text,
  last_name  text,
  is_admin   boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists orders (
  id         text primary key,
  created_at timestamptz not null default now(),
  user_id    uuid references auth.users(id) on delete set null,
  user_email text,
  items      jsonb not null,
  subtotal   numeric not null,
  delivery   numeric not null,
  total      numeric not null,
  status     text not null default 'pending' check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  payment    text not null check (payment in ('cod','bkash')),
  customer   jsonb not null
);

create table if not exists messages (
  id         bigint generated by default as identity primary key,
  name       text not null,
  phone      text not null,
  message    text not null,
  read       boolean not null default false,
  created_at timestamptz not null default now()
);

-- Single-row store settings
create table if not exists settings (
  id                int primary key default 1 check (id = 1),
  announcement      text not null default 'All over Bangladesh delivery · Free delivery on orders over ৳2,000',
  hotline           text not null default '01XXX-XXXXXX',
  email             text not null default 'bdwishbasket@gmail.com',
  address           text not null default 'Dhaka, Bangladesh',
  delivery_inside   numeric not null default 60,
  delivery_outside  numeric not null default 120,
  free_delivery_at  numeric not null default 2000
);
insert into settings (id) values (1) on conflict (id) do nothing;

-- ---------- Helpers ----------

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from profiles where id = auth.uid()), false);
$$;

-- Create a profile row when someone signs up (names come from sign-up metadata)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, first_name, last_name)
  values (new.id, lower(new.email), new.raw_user_meta_data->>'first_name', new.raw_user_meta_data->>'last_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Place an order: checks and deducts stock atomically, prices come from the database
create or replace function public.place_order(p_items jsonb, p_payment text, p_customer jsonb)
returns text language plpgsql security definer set search_path = public as $$
declare
  it jsonb; prod products%rowtype; qty int;
  lines jsonb := '[]'::jsonb; sub numeric := 0; fee numeric; s settings%rowtype;
  new_id text := 'WB' || upper(to_hex((extract(epoch from clock_timestamp()) * 1000)::bigint));
begin
  if p_payment not in ('cod','bkash') then raise exception 'Invalid payment method'; end if;
  if jsonb_array_length(coalesce(p_items, '[]')) = 0 then raise exception 'Cart is empty'; end if;

  for it in select * from jsonb_array_elements(p_items) loop
    qty := (it->>'qty')::int;
    if qty is null or qty < 1 then raise exception 'Invalid quantity'; end if;
    select * into prod from products where id = (it->>'id')::bigint for update;
    if not found or prod.stock < qty then raise exception 'OUT_OF_STOCK'; end if;
    update products set stock = stock - qty where id = prod.id;
    lines := lines || jsonb_build_object('id', prod.id, 'name', prod.name, 'emoji', prod.emoji, 'image', prod.image, 'price', prod.price, 'qty', qty);
    sub := sub + prod.price * qty;
  end loop;

  select * into s from settings where id = 1;
  fee := case when sub >= s.free_delivery_at then 0
              when p_customer->>'area' = 'outside' then s.delivery_outside
              else s.delivery_inside end;

  insert into orders (id, user_id, user_email, items, subtotal, delivery, total, payment, customer)
  values (new_id, auth.uid(), (select email from profiles where id = auth.uid()), lines, sub, fee, sub + fee, p_payment, p_customer);
  return new_id;
end;
$$;

-- Admin: change order status; cancelling returns items to stock (cancelled is final)
create or replace function public.set_order_status(p_id text, p_status text)
returns void language plpgsql security definer set search_path = public as $$
declare o orders%rowtype; it jsonb;
begin
  if not public.is_admin() then raise exception 'Not allowed'; end if;
  select * into o from orders where id = p_id for update;
  if not found or o.status = 'cancelled' or o.status = p_status then return; end if;
  update orders set status = p_status where id = p_id;
  if p_status = 'cancelled' then
    for it in select * from jsonb_array_elements(o.items) loop
      update products set stock = stock + (it->>'qty')::int where id = (it->>'id')::bigint;
    end loop;
  end if;
end;
$$;

-- Guest order lookup (order page / "my orders on this device") without exposing the orders table
create or replace function public.get_orders_by_ids(p_ids text[])
returns setof orders language sql stable security definer set search_path = public as $$
  select * from orders where id = any(p_ids) order by created_at desc;
$$;

-- ---------- Row Level Security ----------

alter table categories enable row level security;
alter table products   enable row level security;
alter table profiles   enable row level security;
alter table orders     enable row level security;
alter table messages   enable row level security;
alter table settings   enable row level security;

drop policy if exists "public read categories" on categories;
create policy "public read categories" on categories for select using (true);
drop policy if exists "admin write categories" on categories;
create policy "admin write categories" on categories for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read products" on products;
create policy "public read products" on products for select using (true);
drop policy if exists "admin write products" on products;
create policy "admin write products" on products for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read settings" on settings;
create policy "public read settings" on settings for select using (true);
drop policy if exists "admin write settings" on settings;
create policy "admin write settings" on settings for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "own or admin read profiles" on profiles;
create policy "own or admin read profiles" on profiles for select using (auth.uid() = id or public.is_admin());

-- Orders are created only through place_order(); customers read their own, admins read all
drop policy if exists "own or admin read orders" on orders;
create policy "own or admin read orders" on orders for select using (auth.uid() = user_id or public.is_admin());

drop policy if exists "anyone send message" on messages;
create policy "anyone send message" on messages for insert with check (true);
drop policy if exists "admin manage messages" on messages;
create policy "admin manage messages" on messages for all using (public.is_admin()) with check (public.is_admin());

grant execute on function public.place_order(jsonb, text, jsonb) to anon, authenticated;
grant execute on function public.get_orders_by_ids(text[]) to anon, authenticated;
grant execute on function public.set_order_status(text, text) to authenticated;

